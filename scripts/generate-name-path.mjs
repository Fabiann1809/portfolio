// Dev-only: generates src/data/intro.ts from a script font.
// Usage: node scripts/generate-name-path.mjs <path-to-Caveat.ttf>
// Font: Caveat (SIL OFL 1.1), github.com/google/fonts/tree/main/ofl/caveat
// The font file is NOT part of the repo; download it to a scratch dir.
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const fontPath = process.argv[2];
if (!fontPath) {
  console.error("Usage: node scripts/generate-name-path.mjs <font.ttf>");
  process.exit(1);
}

const NAME = "Fabian";
const SIZE = 160;
const PAD = 14;

const buf = readFileSync(fontPath);
const font = opentype.parse(
  buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength),
);

let x = 0;
const letters = [];
let minX = Infinity,
  minY = Infinity,
  maxX = -Infinity,
  maxY = -Infinity;

for (const char of NAME) {
  const glyph = font.charToGlyph(char);
  const path = glyph.getPath(x, 0, SIZE);
  const box = path.getBoundingBox();
  minX = Math.min(minX, box.x1);
  minY = Math.min(minY, box.y1);
  maxX = Math.max(maxX, box.x2);
  maxY = Math.max(maxY, box.y2);
  letters.push({ char, path });
  x += (glyph.advanceWidth * SIZE) / font.unitsPerEm;
}

const ox = PAD - minX;
const oy = PAD - minY;
const round = (n) => Math.round(n * 10) / 10;
const width = Math.ceil(maxX - minX + PAD * 2);
const underlineY = maxY + oy + 6;
const height = Math.ceil(underlineY + 22 + PAD);

const paths = letters.map(({ char, path }) => {
  path.commands.forEach((c) => {
    for (const k of ["x", "x1", "x2"]) if (k in c) c[k] += ox;
    for (const k of ["y", "y1", "y2"]) if (k in c) c[k] += oy;
  });
  return { char, d: path.toPathData(1) };
});

const startX = round(PAD + (maxX - minX) * 0.08);
const endX = round(width - PAD);
const flourish = `M${startX} ${round(underlineY)} C${round(startX + (endX - startX) * 0.35)} ${round(underlineY + 14)} ${round(startX + (endX - startX) * 0.7)} ${round(underlineY - 8)} ${endX} ${round(underlineY + 4)}`;

const out = `import type { IntroData } from "@/types/intro";

// GENERATED by scripts/generate-name-path.mjs (font: Caveat, SIL OFL 1.1). Do not edit paths by hand.
export const intro: IntroData = {
  greeting: "hola, soy",
  name: ${JSON.stringify(NAME)},
  viewBox: "0 0 ${width} ${height}",
  letters: ${JSON.stringify(paths, null, 2)},
  flourish: ${JSON.stringify(flourish)},
  timings: {
    letterMs: 260,
    letterOverlapMs: 40,
    fillMs: 350,
    flourishMs: 300,
    exitMs: 600,
    reducedExitMs: 150,
    maxWaitMs: 4000,
  },
};
`;
writeFileSync(new URL("../src/data/intro.ts", import.meta.url), out);
console.log("Wrote src/data/intro.ts", { width, height });
